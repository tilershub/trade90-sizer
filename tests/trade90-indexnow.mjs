import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {urlsFromSitemap,readIndexNowKey} from "../scripts/indexnow-submit.mjs";
const key = readIndexNowKey();
assert.match(key,/^[a-z0-9-]{8,128}$/);
assert.ok(readFileSync(new URL("../public/indexnow-key.txt",import.meta.url),"utf8").includes(key));
const xml=readFileSync(new URL("../dist/sitemap.xml",import.meta.url),"utf8");
const urls=urlsFromSitemap(xml);
assert.ok(urls.includes("https://tradeninety.com/"));
assert.equal(urls.filter(url=>/\/pairs\/[a-z]{3}-[a-z]{3}\/$/.test(url)).length,28);
assert.equal(urls.filter(url=>/\/central-banks\/(fed|ecb|boe|boj|rba|rbnz|boc|snb)\/$/.test(url)).length,8);
assert.ok(urls.every(url=>url.startsWith("https://tradeninety.com/")));
assert.ok(!urls.some(url=>/\/(404|calculator|research|tools)\//.test(url)));
assert.throws(()=>urlsFromSitemap("<urlset/>"),/Not an XML urlset|No canonical/);
assert.throws(()=>urlsFromSitemap('<urlset><url><loc>https://evil.test/</loc></url></urlset>'),/same-origin/);
assert.throws(()=>urlsFromSitemap('<urlset><url><loc>https://tradeninety.com/calculator/eurusd/</loc></url></urlset>'),/Retired/);
assert.throws(()=>urlsFromSitemap('<urlset><url><loc>https://tradeninety.com/</loc></url><url><loc>https://tradeninety.com/</loc></url></urlset>'),/Duplicate/);
console.log("TRADE90 IndexNow validated: "+urls.length+" canonical site URLs, 28 pair pages, 8 bank pages, and proof-of-control key.");
