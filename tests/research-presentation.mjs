import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateOutlookFeed,fetchResearchJson} from '../src/lib/trade90-outlook-feed.js';
import {policyContext,explainPair,evidenceLabel} from '../src/lib/trade90-research-presentation.js';
const feed=JSON.parse(readFileSync('public/data/policy-outlook.json','utf8'));
const now=Date.parse(feed.generatedAt)+1000;
assert.equal(validateOutlookFeed(feed,feed,now),null,'current production contract must refresh');
for(const version of [2,3,4,5,6])assert.equal(validateOutlookFeed({...feed,schemaVersion:version},feed,now),null);
assert.ok(validateOutlookFeed({...feed,schemaVersion:99},feed,now));
assert.ok(validateOutlookFeed({...feed,generatedAt:'invalid'},feed,now));
assert.ok(validateOutlookFeed({...feed,generatedAt:new Date(now+600000).toISOString()},feed,now));
assert.ok(validateOutlookFeed({...feed,generatedAt:new Date(now-600000).toISOString()},feed,now));
assert.ok(validateOutlookFeed({...feed,pairs:{}},feed,now));
assert.ok(validateOutlookFeed({...feed,banks:{}},feed,now));
const broken=structuredClone(feed);delete broken.banks.EUR.drivers[0].latest;
assert.ok(validateOutlookFeed(broken,feed,now));
assert.equal(await fetchResearchJson('/test',async()=>({ok:true,json:async()=>feed})),feed);
await assert.rejects(fetchResearchJson('/test',async()=>({ok:false,status:503})),/503/);
await assert.rejects(fetchResearchJson('/test',(_url,{signal})=>new Promise((_,reject)=>signal.addEventListener('abort',()=>reject(Error('aborted')))),5),/aborted/);
const benchmark={code:'CAD',short:'BoC',benchmark:'Target for overnight rate',rate:2.5,decision:'Hike +25 bp',decisionDate:'2026-10-28',effectiveDate:'2026-10-28',source:'https://www.bankofcanada.ca/decision'};
const bank={policyEvidenceReviewed:true,expiresAt:'2026-11-07',guidance:{publishedDate:'2026-09-02',guidance:'Old hold at 2.25%'},automatedAssessment:{status:'assessed',reason:'Conditional macro pressure',checkedAt:'2026-11-05'}};
const context=policyContext(bank,benchmark,Date.parse('2026-11-05'));
assert.equal(context.current,false);assert.match(context.historicalLabel,/superseded/);
assert.match(context.headline,/2.50%/);assert.doesNotMatch(context.interpretation,/2.25/);
const currentBank={...bank,guidance:{...bank.guidance,publishedDate:'2026-10-28'}};
assert.equal(policyContext(currentBank,benchmark,Date.parse('2026-11-05')).current,true);
assert.equal(policyContext(currentBank,benchmark,Date.parse('2026-11-08')).current,false);
currentBank.automatedAssessment.evidence={newerOfficialDecision:{date:'2026-11-04'}};
assert.equal(policyContext(currentBank,benchmark,Date.parse('2026-11-05')).current,false);
assert.match(evidenceLabel('exploratory_macro'),/macro evidence only/);
